/** Production-only checks for offline web use and project-folder routing. */
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { getInitialDemoState } from '../src/services/repository.ts';
import { readPersonalRecordFixture } from './qa-personal-record-fixtures.mjs';
const root = process.env.ODA_QA_URL || 'http://localhost:4173';
const project = process.env.ODA_PROJECT_QA_URL || 'http://localhost:4174/one-decision-away/';
const out = process.env.ODA_PLATFORM_QA_OUT || 'artifacts/platform';
mkdirSync(out, { recursive: true });
const report = { at: new Date().toISOString(), checks: [], errors: [] };
const pass = message => { report.checks.push(message); console.log(`PASS ${message}`); };
const browser = await chromium.launch({ executablePath: process.env.ODA_CHROMIUM || '/usr/bin/chromium', args: ['--no-sandbox'] });
const seed = getInitialDemoState(); seed.profile.onboardingStep = 'completed'; seed.profile.displayName = 'Maya'; seed.profile.locale = 'en';
const key = 'one_decision_away_app_data_v1';
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: 'allow', reducedMotion: 'reduce', timezoneId: 'Europe/Istanbul' });
  await context.addInitScript(([key, seed]) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(seed)); localStorage.setItem('oda_locale', 'en'); }, [key, seed]);
  const page = await context.newPage(); page.on('pageerror', error => report.errors.push(error.message));
  await page.goto(`${root}/app`); await page.locator('#set-one-decision').waitFor();
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await page.reload(); await page.locator('#set-one-decision').waitFor();
  await page.goto(`${root}/app/courses`); await page.locator('#course-search').waitFor();
  await page.goto(`${root}/app/support`); await page.locator('#support-contact').waitFor();
  await page.goto(`${root}/app/settings`); await page.getByRole('button', { name: 'Download backup', exact: true }).waitFor();
  await context.setOffline(true);
  await page.goto(`${root}/app`); await page.locator('#set-one-decision').waitFor();
  await page.locator('#today-decision-input').fill('Read the next two pages');
  await page.getByRole('button', { name: 'Set decision', exact: true }).click();
  // Wait for acknowledged persistence, rather than reload an in-flight save.
  await page.getByText('Read the next two pages', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.reload(); await page.locator('#set-one-decision').waitFor();
  assert.ok(await page.getByText('Read the next two pages', { exact: true }).isVisible());
  pass('installed web shell reloads offline and preserves a new daily decision');
  await page.goto(`${root}/app/courses`); await page.locator('#course-search').waitFor();
  assert.equal(await page.locator('.oda-course-row').count(), 18);
  await page.locator('.oda-course-row').first().click(); await page.locator('#course-reflection').waitFor();
  await page.locator('#course-reflection').fill('My first step can stay small.');
  const savedCourse = await readPersonalRecordFixture(page);
  assert.ok(Object.values(savedCourse.courseProgress.lessons).some(lesson => lesson.reflection === 'My first step can stay small.'));
  await page.reload(); await page.locator('#course-reflection').waitFor();
  assert.equal(await page.locator('#course-reflection').inputValue(), 'My first step can stay small.');
  pass('previously visited course content and saved reflection work offline');
  await page.goto(`${root}/app/settings`); await page.getByRole('button', { name: 'Download backup', exact: true }).waitFor();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download backup', exact: true }).click(); await download;
  pass('backup download remains available offline');
  await page.goto(`${root}/app/support`); await page.locator('#support-contact').waitFor();
  await page.screenshot({ path: `${out}/support-offline.png` });
  pass('previously visited in-app support reloads offline');
  await page.goto(`${root}/support.html`); await page.locator('#contact-en').waitFor();
  pass('standalone recovery support is precached for offline use');
  await context.setOffline(false);
  await page.reload(); await page.locator('#contact-en').waitFor();
  await context.setOffline(true);
  await page.goto(`${root}/app`); await page.locator('#set-one-decision').waitFor();
  assert.ok(await page.getByText('Read the next two pages', { exact: true }).isVisible());
  pass('visiting standalone support preserves the application offline shell');
  await context.close();

  const projectContext = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block', reducedMotion: 'reduce' });
  await projectContext.addInitScript(([key, seed]) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(seed)); localStorage.setItem('oda_locale', 'en'); }, [key, seed]);
  const nested = await projectContext.newPage(); nested.on('pageerror', error => report.errors.push(error.message));
  await nested.goto(`${project}#/app/courses`); await nested.locator('#course-search').waitFor();
  assert.equal(await nested.locator('.oda-course-row').count(), 18);
  await nested.reload(); await nested.locator('#course-search').waitFor();
  assert.ok(nested.url().includes('/one-decision-away/#/app/courses'));
  pass('project-folder course hash route loads and survives direct reload');
  const assets = await nested.evaluate(() => [...document.querySelectorAll('script[src]')].map(script => script.getAttribute('src')));
  assert.ok(assets.filter(src => src.includes('assets/')).every(src => src.startsWith('/one-decision-away/')));
  pass('project build requests its own assets under the deployment base');
  await nested.screenshot({ path: `${out}/project-courses-mobile.png` });
  await projectContext.close();
  assert.deepEqual(report.errors, []); pass('no uncaught errors in offline and project-route checks'); report.status = 'passed';
} catch (error) { report.status = 'failed'; report.failure = String(error.stack || error); console.error(error); process.exitCode = 1; }
finally { writeFileSync(`${out}/report.json`, JSON.stringify(report, null, 2)); await browser.close(); }
